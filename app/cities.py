def _key(s):
    """'Санкт-Петербург', 'санкт петербург', 'Ёлки' -> одинаковые ключи без регистра/дефисов/ё."""
    return re.sub(r"[\s\-]+", " ", str(s).strip().lower().replace("ё", "е"))


_INDEX = {_key(n): n for n in _RAW}
_ALIAS = {_key(a): c for a, c in ALIASES.items()}
_cache = {}


def _pt(t):
    return {"lat": t[0], "lon": t[1]}


def is_unsupported(name):
    return _key(name) in UNSUPPORTED


def get_city(name):
    """-> {'name', 'center': {lat,lon}, 'airport': {lat,lon}, 'source'} или None."""
    if not name or not str(name).strip():
        return None
    k = _key(name)
    canon = _INDEX.get(k) or _ALIAS.get(k)
    if canon:
        center, airport = _RAW[canon]
        return {"name": canon, "center": _pt(center), "airport": _pt(airport or center),
                "iata": IATA.get(canon), "source": "справочник"}
    if k in UNSUPPORTED:
        return None
    if k in _cache:
        return _cache[k]
    result = None
    if twogis.KEY:                         # неизвестный город: ищем через 2GIS
        center = twogis.geocode(str(name).strip())
        if center:
            airport = twogis.geocode(f"{str(name).strip()}, аэропорт") or center
            result = {"name": str(name).strip().title(), "center": center,
                      "airport": airport, "iata": None, "source": "2GIS"}
    _cache[k] = result
    return result


def haversine_km(a, b):
    """Расстояние по прямой между {'lat','lon'} и {'lat','lon'}, км."""
    la1, lo1, la2, lo2 = map(radians, (a["lat"], a["lon"], b["lat"], b["lon"]))
    h = sin((la2 - la1) / 2) ** 2 + cos(la1) * cos(la2) * sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371 * asin(sqrt(h))
